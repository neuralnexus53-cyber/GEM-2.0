function escapeRegExp(s: string): string {
  const escaped = s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const prefix = /^[a-zA-Z0-9]/.test(s) ? '(?<![\\w/.-])' : '';
  const suffix = /[a-zA-Z0-9]$/.test(s) ? '(?![\\w/.-])' : '';
  return `${prefix}${escaped}${suffix}`;
}



