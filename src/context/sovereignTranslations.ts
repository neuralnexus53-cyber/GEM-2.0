export function getVocabRegex(): RegExp {

  if (!compiledVocabRegex) {

    compiledVocabRegex = new RegExp(

      VOCAB_PHRASES_SORTED.map(escapeRegExp).join('|'),

      'gi'

    );

  }

  return compiledVocabRegex;

}



export function getVocabTranslation(phrase: string, lang: LanguageCode): string | null {

  if (lang === 'en') return phrase;

  const match = VOCAB_MAP.get(phrase.toLowerCase().trim());

  if (match && match[lang]) {

    return match[lang];

  }

  return null;

}



// Universal Reverse Vocabulary Map: maps every non-English term in any supported Indian language back to its canonical English

export const REVERSE_VOCAB_MAP = new Map<string, string>();



const langCodes: (keyof VocabEntry)[] = ['hi', 'or', 'mr', 'ta', 'te', 'bn', 'gu', 'kn', 'ml', 'pa'];

for (const entry of SOVEREIGN_VOCABULARY) {

  REVERSE_VOCAB_MAP.set(entry.en.trim(), entry.en.trim());

  REVERSE_VOCAB_MAP.set(entry.en.toLowerCase().trim(), entry.en.trim());

  for (const lk of langCodes) {

    const val = entry[lk];

    if (val && typeof val === 'string' && val.trim() && val !== entry.en) {

      REVERSE_VOCAB_MAP.set(val.trim(), entry.en.trim());

      REVERSE_VOCAB_MAP.set(val.toLowerCase().trim(), entry.en.trim());

    }

  }

}



let compiledReverseVocabRegex: RegExp | null = null;

export function getReverseVocabRegex(): RegExp | null {

  if (!compiledReverseVocabRegex) {

    const keys = Array.from(REVERSE_VOCAB_MAP.keys()).filter((k) => k.length > 1);

    if (keys.length === 0) return null;

    keys.sort((a, b) => b.length - a.length);

    compiledReverseVocabRegex = new RegExp(keys.map(escapeRegExp).join('|'), 'g');

  }

  return compiledReverseVocabRegex;

}



// Universal Dictionary Registration: registers both forward and reverse translations across all 11 official languages

export function registerDictionary(dict: Record<string, Record<string, string>>) {

  if (!dict || !dict.en) return;

  const enDict = dict.en;

  const targetLangs: LanguageCode[] = ['hi', 'or', 'mr', 'ta', 'te', 'bn', 'gu', 'kn', 'ml', 'pa'];



  for (const [key, enVal] of Object.entries(enDict)) {

    if (!enVal || typeof enVal !== 'string') continue;

    const trimmedEn = enVal.trim();

    const lowerEn = trimmedEn.toLowerCase();



    // 1. Forward mapping into VOCAB_MAP

    let entry = VOCAB_MAP.get(lowerEn);

    if (!entry) {

      entry = {

        en: trimmedEn,

        hi: '',

        or: '',

        mr: '',

        ta: '',

        te: '',

        bn: '',

        gu: '',

        kn: '',

        ml: '',

        pa: ''

      };

      VOCAB_MAP.set(lowerEn, entry);

      if (!VOCAB_PHRASES_SORTED.includes(trimmedEn)) {

        VOCAB_PHRASES_SORTED.push(trimmedEn);

      }

    }



    // Also link dictionary key itself (e.g. 'nav.home')

    VOCAB_MAP.set(key.toLowerCase().trim(), entry);



    // 2. Bidirectional translations

    for (const lk of targetLangs) {

      const langObj = dict[lk];

      if (!langObj) continue;

      const transVal = langObj[key];

      if (transVal && typeof transVal === 'string' && transVal.trim()) {

        const trimmedTrans = transVal.trim();

        entry[lk] = trimmedTrans;



        // Map foreign word back to English

        REVERSE_VOCAB_MAP.set(trimmedTrans, trimmedEn);

        REVERSE_VOCAB_MAP.set(trimmedTrans.toLowerCase(), trimmedEn);

      }

    }



    // Self mapping for English

    REVERSE_VOCAB_MAP.set(trimmedEn, trimmedEn);

    REVERSE_VOCAB_MAP.set(lowerEn, trimmedEn);

  }



  // Re-sort sorted phrases descending by length so longer phrases match before sub-words

  VOCAB_PHRASES_SORTED.sort((a, b) => b.length - a.length);



  // Invalidate compiled regular expressions so they rebuild with full dictionary

  compiledVocabRegex = null;

  compiledReverseVocabRegex = null;

  translationCache.clear();

}



// Backward compatibility alias

export const registerReverseDictionary = registerDictionary;



// Clear all Google Translate cookies across all path and domain variations

export function clearGoogleTranslateCookies() {

  if (typeof window === 'undefined') return;

  try {

    const hostname = window.location.hostname;

    const domainParts = hostname.split('.');

    const domains = [hostname, '.' + hostname, ''];

    while (domainParts.length > 1) {

      domains.push('.' + domainParts.join('.'));

      domainParts.shift();

    }

    const paths = ['/', window.location.pathname];

    for (const d of domains) {

      for (const p of paths) {

        const dAttr = d ? `; domain=${d}` : '';

        const pAttr = p ? `; path=${p}` : '';

        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 GMT; max-age=0${dAttr}${pAttr}`;

      }

    }

  } catch (e) {}

}



// Memory tracking of original text nodes and O(1) translation cache

const originalTextMap = new WeakMap<Node, string>();

const translationCache = new Map<string, string>();

let activeObserver: MutationObserver | null = null;

let isTranslating = false;



// Sovereign Ultra High-Speed DOM Walker: translates entire active page in < 5ms using native TreeWalker and compiled regex

export function walkAndTranslateDom(lang: LanguageCode) {

  if (typeof window === 'undefined' || !document.body) return;



  const root = document.getElementById('root') || document.body;

  const regex = getVocabRegex();

  const revRegex = getReverseVocabRegex();



  const translateSingleTextNode = (node: Node) => {

    const text = node.textContent;

    if (!text || !text.trim()) return;



    // Step 1: Reconstruct or retrieve the canonical English baseline

    let englishText = originalTextMap.get(node);



    if (!englishText) {

      const current = node.textContent || '';

      const trimmedCurrent = current.trim();



      // Check if current text contains translated words in any language (e.g. Odia, Malayalam, etc.)

      if (REVERSE_VOCAB_MAP.has(trimmedCurrent)) {

        englishText = current.replace(trimmedCurrent, REVERSE_VOCAB_MAP.get(trimmedCurrent)!);

      } else if (revRegex && revRegex.test(current)) {

        revRegex.lastIndex = 0;

        englishText = current.replace(revRegex, (matched) => {

          return REVERSE_VOCAB_MAP.get(matched) || REVERSE_VOCAB_MAP.get(matched.toLowerCase()) || REVERSE_VOCAB_MAP.get(matched.trim()) || matched;

        });

      } else {

        englishText = current;

      }

      originalTextMap.set(node, englishText);

    } else if (revRegex && revRegex.test(englishText)) {

      // Clean up any foreign characters that slipped into cached text

      revRegex.lastIndex = 0;

      englishText = englishText.replace(revRegex, (matched) => {

        return REVERSE_VOCAB_MAP.get(matched) || REVERSE_VOCAB_MAP.get(matched.toLowerCase()) || REVERSE_VOCAB_MAP.get(matched.trim()) || matched;

      });

      originalTextMap.set(node, englishText);

    }



    // If target is English, restore the pure English text

    if (lang === 'en') {

      if (node.textContent !== englishText) {

        node.textContent = englishText;

      }

      return;

    }



    const trimmedEnglish = englishText.trim();

    if (!trimmedEnglish) return;



    // Step 2: Translate from the clean English baseline to the target language

    const cacheKey = `${lang}:${trimmedEnglish}`;

    let translated = translationCache.get(cacheKey);



    if (translated === undefined) {

      // 1. Direct whole-string match from English to target language

      const exact = getVocabTranslation(trimmedEnglish, lang);

      if (exact && exact !== trimmedEnglish) {

        translated = englishText.replace(trimmedEnglish, exact);

      } else if (regex) {

        // 2. Single-pass compiled RegExp native C++ replacement from English to target language

        let hasChange = false;

        regex.lastIndex = 0;

        translated = englishText.replace(regex, (matched) => {

          const trans = getVocabTranslation(matched, lang);

          if (trans && trans !== matched) {

            hasChange = true;

            return trans;

          }

          return matched;

        });

        if (!hasChange) {

          translated = englishText;

        }

      } else {

        translated = englishText;

      }

      translationCache.set(cacheKey, translated);

    }



    if (translated !== node.textContent) {

      node.textContent = translated;

    }

  };



  // Helper for translating any HTML attribute (placeholder, title, aria-label, alt, value)

  const translateSingleAttribute = (

    el: Element,

    attrName: string,

    storageAttr: string

  ) => {

    const currentVal = el.getAttribute(attrName);

    if (!currentVal || !currentVal.trim()) return;



    let origVal = el.getAttribute(storageAttr);

    if (!origVal) {

      let clean = currentVal.trim();

      if (REVERSE_VOCAB_MAP.has(clean)) {

        clean = REVERSE_VOCAB_MAP.get(clean)!;

      } else if (revRegex && revRegex.test(clean)) {

        revRegex.lastIndex = 0;

        clean = clean.replace(revRegex, (m) => REVERSE_VOCAB_MAP.get(m) || REVERSE_VOCAB_MAP.get(m.toLowerCase()) || REVERSE_VOCAB_MAP.get(m.trim()) || m);

      }

      origVal = clean;

      el.setAttribute(storageAttr, origVal);

    }



    if (lang === 'en') {

      if (currentVal !== origVal) {

        el.setAttribute(attrName, origVal);

      }

    } else {

      const exact = getVocabTranslation(origVal.trim(), lang);

      let trans = exact;

      if (!trans && regex) {

        regex.lastIndex = 0;

        trans = origVal.replace(regex, (m) => getVocabTranslation(m, lang) || m);

      }

      if (trans && trans !== currentVal) {

        el.setAttribute(attrName, trans);

      }

    }

  };



  // Translate all small interactive attributes across the DOM

  const translateAttributes = (scope: Element) => {

    // 1. Input and Textarea placeholders

    const placeholders = scope.querySelectorAll('input[placeholder], textarea[placeholder]');

    placeholders.forEach((el) => {

      translateSingleAttribute(el, 'placeholder', 'data-orig-placeholder');

    });



    // 2. Titles (Tooltips, button hover labels)

    const titles = scope.querySelectorAll('[title]');

    titles.forEach((el) => {

      if (el.classList.contains('notranslate') || el.closest('.notranslate') || el.closest('[translate="no"]')) return;

      translateSingleAttribute(el, 'title', 'data-orig-title');

    });



    // 3. Aria-labels (Accessible button names, close buttons, badges)

    const ariaLabels = scope.querySelectorAll('[aria-label]');

    ariaLabels.forEach((el) => {

      if (el.classList.contains('notranslate') || el.closest('.notranslate') || el.closest('[translate="no"]')) return;

      translateSingleAttribute(el, 'aria-label', 'data-orig-aria-label');

    });



    // 4. Alt text on images

    const altImgs = scope.querySelectorAll('img[alt]');

    altImgs.forEach((el) => {

      if (el.classList.contains('notranslate') || el.closest('.notranslate') || el.closest('[translate="no"]')) return;

      translateSingleAttribute(el, 'alt', 'data-orig-alt');

    });



    // 5. Button and submit input values

    const buttonInputs = scope.querySelectorAll('input[type="button"], input[type="submit"]');

    buttonInputs.forEach((el) => {

      translateSingleAttribute(el, 'value', 'data-orig-value');

    });

  };



  // Ultra-fast browser C++ native TreeWalker

  isTranslating = true;

  try {

    const walker = document.createTreeWalker(

      root,

      NodeFilter.SHOW_TEXT,

      {

        acceptNode: (n) => {

          const parent = n.parentElement;

          if (!parent) return NodeFilter.FILTER_REJECT;

          const tag = parent.tagName.toLowerCase();

          if (

            tag === 'script' ||

            tag === 'style' ||

            tag === 'code' ||

            tag === 'pre' ||

            tag === 'textarea' ||

            parent.isContentEditable ||

            parent.classList.contains('notranslate') ||

            parent.closest('[translate="no"]') ||

            parent.closest('.notranslate') ||

            parent.id === 'google_translate_element'

          ) {

            return NodeFilter.FILTER_REJECT;

          }

          return NodeFilter.FILTER_ACCEPT;

        }

      }

    );



    let textNode: Node | null;

    while ((textNode = walker.nextNode())) {

      translateSingleTextNode(textNode);

    }



    translateAttributes(root);



    // In English mode, clean up any residual <font> tags Google Translate may have inserted

    if (lang === 'en') {

      const fontTags = root.querySelectorAll('font');

      fontTags.forEach((font) => {

        const parent = font.parentNode;

        if (parent) {

          while (font.firstChild) {

            parent.insertBefore(font.firstChild, font);

          }

          parent.removeChild(font);

        }

      });

    }

  } finally {

    isTranslating = false;

  }



  // Active observer for dynamically added modal or route elements

  if (activeObserver) {

    activeObserver.disconnect();

    activeObserver = null;

  }



  if (lang !== 'en') {

    activeObserver = new MutationObserver((mutations) => {

      if (isTranslating) return;

      for (const m of mutations) {

        for (let i = 0; i < m.addedNodes.length; i++) {

          const added = m.addedNodes[i];

          if (added.nodeType === Node.TEXT_NODE) {

            translateSingleTextNode(added);

          } else if (added.nodeType === Node.ELEMENT_NODE) {

            const el = added as HTMLElement;

            if (el.id === 'google_translate_element' || el.classList.contains('notranslate') || el.closest('[translate="no"]')) continue;

            const subWalker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, null);

            let subNode: Node | null;

            while ((subNode = subWalker.nextNode())) {

              translateSingleTextNode(subNode);

            }

            translateAttributes(el);

          }

        }

      }

    });

    activeObserver.observe(root, { childList: true, subtree: true });

  }

}



// Google Translate Bridge: triggers Google Translate widget for full page translation

export function triggerGoogleTranslate(lang: LanguageCode): boolean {

  if (typeof window === 'undefined') return false;



  try {

    const hostname = window.location.hostname;



    if (lang === 'en') {

      // 1. Completely remove all googtrans cookies

      clearGoogleTranslateCookies();



      // 2. Reset Google Translate dropdown (.goog-te-combo) to default option (index 0 / "")

      const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;

      if (select) {

        let enOptIndex = 0;

        for (let i = 0; i < select.options.length; i++) {

          const opt = select.options[i];

          if (opt.value === '' || opt.value === 'en') {

            enOptIndex = i;

            break;

          }

        }

        select.selectedIndex = enOptIndex;

        select.value = select.options[enOptIndex]?.value || '';

        select.dispatchEvent(new Event('change', { bubbles: true, cancelable: true }));

        if (typeof (select as any).onchange === 'function') {

          (select as any).onchange(new Event('change'));

        }

      }



      // 3. Remove Google Translate classes and reset HTML lang

      document.documentElement.classList.remove('translated-ltr', 'translated-rtl');

      if (document.body) {

        document.body.classList.remove('translated-ltr', 'translated-rtl');

        document.body.style.setProperty('top', '0px', 'important');

        document.body.style.setProperty('position', 'static', 'important');

      }

      document.documentElement.lang = 'en';



      return true;

    }



    // Otherwise non-English

    const targetVal = `/en/${lang}`;

    document.cookie = `googtrans=${targetVal}; path=/; max-age=31536000`;

    if (hostname && hostname !== 'localhost' && hostname !== '127.0.0.1') {

      document.cookie = `googtrans=${targetVal}; domain=.${hostname}; path=/; max-age=31536000`;

      document.cookie = `googtrans=${targetVal}; domain=${hostname}; path=/; max-age=31536000`;

    }



    // Find .goog-te-combo

    const select = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;

    if (select) {

      let optionFound = false;

      for (let i = 0; i < select.options.length; i++) {

        const opt = select.options[i];

        if (opt.value === lang || opt.value.toLowerCase().startsWith(lang)) {

          select.selectedIndex = i;

          optionFound = true;

          break;

        }

      }



      if (!optionFound) {

        select.value = lang;

      }



      select.dispatchEvent(new Event('change', { bubbles: true, cancelable: true }));

      if (typeof (select as any).onchange === 'function') {

        (select as any).onchange(new Event('change'));

      }



      // Proactively sanitize DOM to eliminate any intrusive Google Translate top bar

      const purgeBanners = () => {

        if (typeof document !== 'undefined') {

          if (document.body) {

            if (document.body.style.top && document.body.style.top !== '0px') {

              document.body.style.setProperty('top', '0px', 'important');

            }

            if (document.body.style.position === 'relative') {

              document.body.style.setProperty('position', 'static', 'important');

            }

          }

          const banners = document.querySelectorAll(

            'body > .skiptranslate, body > div[class*="skiptranslate"], iframe.goog-te-banner-frame, iframe[id^=":"], .VIpgJd-ZVi9od-aZ2wEe-wOHMy, .VIpgJd-ZVi9od-aZ2wEe-Oxf5Fd, #goog-gt-tt'

          );

          banners.forEach((el) => {

            (el as HTMLElement).style.setProperty('display', 'none', 'important');

            (el as HTMLElement).style.setProperty('visibility', 'hidden', 'important');

            (el as HTMLElement).style.setProperty('height', '0px', 'important');

          });

        }

      };



      purgeBanners();

      setTimeout(purgeBanners, 50);

      setTimeout(purgeBanners, 250);

      setTimeout(purgeBanners, 600);



      return true;

    }

  } catch (e) {

    console.warn('Google translate trigger note:', e);

  }

  return false;

}

